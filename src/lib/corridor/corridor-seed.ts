import type {
	CorridorData,
	RouteSegment,
	TransportMode,
} from "./corridor-types";

/** Builds one seed leg; fares are [reference, min, max] in COP. */
function segment(
	code: string,
	origin: string,
	destination: string,
	mode: TransportMode,
	distanceKm: number,
	minutes: number,
	[reference, min, max]: [number, number, number],
	green: boolean,
	accessible: boolean,
	floodZone: string | null,
): RouteSegment {
	return {
		code,
		origin_stop_code: origin,
		destination_stop_code: destination,
		transport_mode: mode,
		distance_km: distanceKm,
		estimated_minutes: minutes,
		reference_fare_cop: reference,
		fare_min_cop: min,
		fare_max_cop: max,
		is_green_route: green,
		is_accessible: accessible,
		flood_zone_code: floodZone,
		is_simulated: true,
	};
}

